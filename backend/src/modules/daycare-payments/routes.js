'use strict';
const router=require('express').Router();
const rateLimit=require('express-rate-limit');
const auth=require('../../middleware/auth');
const {allowRoles}=require('../../middleware/rbac');
const service=require('./service').createDaycarePayments(require('../../config/db'));
const wrap=fn=>async(req,res,next)=>{try{res.json(await fn(req));}catch(error){next(error);}};
const receiptLimit=rateLimit({windowMs:15*60*1000,max:40,standardHeaders:true,legacyHeaders:false});
router.use(auth,allowRoles('admin','parent'));
router.get('/settings',allowRoles('admin'),wrap(req=>service.settings(req.user)));
router.put('/settings',allowRoles('admin'),wrap(req=>service.saveSettings(req.body,req.user)));
router.get('/receiving-accounts',wrap(req=>service.receivingAccounts(req.user)));
router.get('/requests',wrap(req=>service.list(req.query,req.user)));
router.post('/requests',allowRoles('parent'),wrap(req=>service.create(req.body,req.user)));
router.get('/requests/:id',wrap(req=>service.get(req.params.id,req.user)));
router.post('/requests/:id/verify',allowRoles('parent'),receiptLimit,wrap(req=>service.verify(req.params.id,req.body,req.user)));
router.post('/requests/:id/review',allowRoles('admin'),wrap(req=>service.review(req.params.id,req.body,req.user)));
router.post('/requests/:id/resolve',allowRoles('admin'),wrap(req=>service.resolve(req.params.id,req.body,req.user)));
module.exports=router;
